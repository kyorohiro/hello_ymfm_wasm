// CPU-free adapter over the existing MIT sidera endpoint's standalone batch API.
import {SID_PAL_CLOCK} from './sid.js';

const CAPACITY = 4096;
const integer = (value, min, max, label) => {
  if (!Number.isInteger(value) || value < min || value > max) throw new RangeError(`${label} must be an integer ${min}..${max}`);
  return value;
};
const REQUIRED = ['sid8p_create','sid8p_destroy','sid8p_reset','sid8p_run','sid8p_output','sid8p_output_frames',
  'sid8p_write','sid8p_read','sid8p_error','sid8p_model','sid8p_rate','sid8p_written',
  'sid8p_cycles_lo','sid8p_cycles_hi','sid8p_frames_lo','sid8p_frames_hi','sid8p_calibration','sid8p_cutoff_calibration'];

/** One mono PAL 8580 Preview, with no C64 CPU and no per-chip-cycle JS loop.
 * Each public register access advances one chip tick before committing its bus
 * access, retaining any sample generated by that tick. Rust advances batches;
 * JavaScript only copies output frames and applies the existing 12 Hz host DC
 * blocker. Per-voice Envelope/phase observations are unavailable, not zero.
 */
export class Sid8580Core {
  /** @param {{sampleRate?:number,clockHz?:number,model?:'8580',wasmUrl?:URL|string,wasmBinary?:BufferSource,signal?:AbortSignal}} [options] */
  static async create({sampleRate = 48000, clockHz = SID_PAL_CLOCK, model = '8580', wasmUrl, wasmBinary, signal} = {}) {
    integer(sampleRate, 8000, 96000, 'SID sampleRate');
    if (clockHz !== SID_PAL_CLOCK) throw new RangeError('8580 Preview requires the PAL clock 985248 Hz');
    if (model !== '8580') throw new RangeError('Sid8580Core requires model 8580');
    signal?.throwIfAborted();
    let bytes = wasmBinary;
    if (!bytes) {
      const response = await fetch(wasmUrl ?? new URL('../generated/sid8580-machine/sid8580-endpoint.wasm', import.meta.url), {signal});
      if (!response.ok) throw new Error(`8580 WASM could not be loaded (${response.status})`);
      bytes = await response.arrayBuffer();
    }
    signal?.throwIfAborted();
    const module = await WebAssembly.compile(bytes);
    if (WebAssembly.Module.imports(module).length) throw new Error('8580 standalone module must not import host callbacks');
    const instance = await WebAssembly.instantiate(module, {});
    signal?.throwIfAborted();
    const api = instance.exports;
    if (!(api.memory instanceof WebAssembly.Memory) || REQUIRED.some(name => typeof api[name] !== 'function')) throw new Error('8580 standalone batch API is incomplete');
    const handle = api.sid8p_create(sampleRate, 1);
    if (!handle) throw new Error('8580 core allocation failed');
    try {
      if (api.sid8p_model(handle) !== 1 || api.sid8p_rate(handle) !== sampleRate
        || api.sid8p_calibration(handle) !== 0 || api.sid8p_cutoff_calibration(handle) !== 0) throw new Error('8580 target/profile mismatch');
      signal?.throwIfAborted();
      return new Sid8580Core(api, handle, sampleRate);
    } catch (error) { api.sid8p_destroy(handle); throw error; }
  }
  constructor(exports, handle, sampleRate) {
    this.exports = exports; this.handle = handle; this.sampleRate = sampleRate;
    this.clockHz = SID_PAL_CLOCK; this.model = '8580'; this.modelStatus = 'preview';
    this.registers = new Uint8Array(32); this.queue = new Float32Array(CAPACITY);
    this.queueRead = 0; this.queueCount = 0; this.phase = 0;
    this.previousInput = 0; this.previousOutput = 0;
    this.dcPole = Math.exp(-2 * Math.PI * 12 / sampleRate);
  }
  assertOpen() { if (!this.handle) throw new Error('8580 core is disposed'); }
  _run(cycles) {
    const predicted = Math.floor((this.phase + cycles * this.sampleRate) / this.clockHz);
    if (predicted > CAPACITY - this.queueCount) throw new Error('SID access queue is full; render audio before more register accesses');
    const frames = this.exports.sid8p_run(this.handle, cycles) >>> 0;
    if (frames === 0xffffffff || frames !== predicted || frames !== this.exports.sid8p_output_frames(this.handle)) throw new Error(`8580 render failed (${this.exports.sid8p_error(this.handle)})`);
    this.phase = (this.phase + cycles * this.sampleRate) % this.clockHz;
    const samples = new Int16Array(this.exports.memory.buffer, this.exports.sid8p_output(this.handle), frames);
    for (let i = 0; i < frames; i++) {
      const input = samples[i] / 32768, output = input - this.previousInput + this.dcPole * this.previousOutput;
      this.previousInput = input; this.previousOutput = output;
      this.queue[(this.queueRead + this.queueCount) % CAPACITY] = output; this.queueCount++;
    }
  }
  _accessTick() {
    // Match SidCore's bounded access queue even when this particular tick would
    // not generate a sample. A rejected access must not advance the chip.
    if (this.queueCount === CAPACITY) throw new Error('SID access queue is full; render audio before more register accesses');
    this._run(1);
  }
  writeRegister(register, value) {
    this.assertOpen(); integer(register, 0, 31, 'SID register'); integer(value, 0, 255, 'SID value');
    this._accessTick();
    if (!this.exports.sid8p_write(this.handle, register, value)) throw new Error(`8580 register write failed (${this.exports.sid8p_error(this.handle)})`);
    this.registers[register] = value;
  }
  readRegister(register) {
    this.assertOpen(); integer(register, 0, 31, 'SID register'); this._accessTick();
    const value = this.exports.sid8p_read(this.handle, register);
    if (value > 255) {
      const error = new Error(register === 25 || register === 26 ? '8580 POT input reads are unsupported' : '8580 register read failed');
      error.code = this.exports.sid8p_error(this.handle); throw error;
    }
    return value;
  }
  renderInto(output) {
    this.assertOpen(); if (!(output instanceof Float32Array)) throw new TypeError('SID output must be Float32Array');
    for (let offset = 0; offset < output.length;) {
      if (!this.queueCount) {
        const frames = Math.min(CAPACITY, output.length - offset);
        const cycles = Math.ceil((frames * this.clockHz - this.phase) / this.sampleRate);
        this._run(cycles);
      }
      const count = Math.min(this.queueCount, output.length - offset);
      for (let i = 0; i < count; i++) output[offset + i] = this.queue[(this.queueRead + i) % CAPACITY];
      this.queueRead = (this.queueRead + count) % CAPACITY; this.queueCount -= count; offset += count;
    }
    return output;
  }
  render(frames) { integer(frames, 0, this.sampleRate * 600, 'SID frames'); return this.renderInto(new Float32Array(frames)); }
  reset() {
    this.assertOpen(); if (!this.exports.sid8p_reset(this.handle)) throw new Error('8580 reset failed');
    this.registers.fill(0); this.queue.fill(0); this.queueRead = this.queueCount = this.phase = 0;
    this.previousInput = this.previousOutput = 0;
  }
  getState() {
    this.assertOpen();
    const a = this.exports, h = this.handle;
    return {model: this.model, modelStatus: this.modelStatus, clockHz: this.clockHz, sampleRate: this.sampleRate,
      cycles: (a.sid8p_cycles_lo(h) >>> 0) + (a.sid8p_cycles_hi(h) >>> 0) * 2 ** 32,
      frames: (a.sid8p_frames_lo(h) >>> 0) + (a.sid8p_frames_hi(h) >>> 0) * 2 ** 32,
      registers: Array.from(this.registers), voices: Array.from({length: 3}, () => ({envelope: null, phase: null})),
      profiles: {resonance: !!a.sid8p_calibration(h), cutoff: !!a.sid8p_cutoff_calibration(h)},
      hostDcHz: 12, cpuFree: true, batchClocking: true};
  }
  dispose() {
    if (!this.handle) return;
    this.exports.sid8p_destroy(this.handle); this.handle = 0;
    this.queue.fill(0); this.queueRead = this.queueCount = 0;
  }
}
