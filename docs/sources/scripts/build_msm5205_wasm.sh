set -eu
ROOT_DIR=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)
cd "$ROOT_DIR"
OUT_DIR="${1:-$ROOT_DIR/dist/wasm}"
mkdir -p "$OUT_DIR"
OUT_DIR=$(CDPATH= cd -- "$OUT_DIR" && pwd)
"${EMCC:-emcc}" "$ROOT_DIR/native/msm5205/msm5205_pcm.c" "$ROOT_DIR/native/msm5205/msm5205_wasm.c" \
  -I"$ROOT_DIR/native/msm5205" \
  -std=c11 -O2 -ffp-contract=off -sSTANDALONE_WASM=1 \
  -sALLOW_MEMORY_GROWTH=0 -sINITIAL_MEMORY=131072 -sSTACK_SIZE=16384 \
  --no-entry -Wl,--export-memory \
  -Wl,--export=msm5205_wasm_init -Wl,--export=msm5205_wasm_input \
  -Wl,--export=msm5205_wasm_left -Wl,--export=msm5205_wasm_right \
  -Wl,--export=msm5205_wasm_prepare -Wl,--export=msm5205_wasm_play \
  -Wl,--export=msm5205_wasm_stop -Wl,--export=msm5205_wasm_reset \
  -Wl,--export=msm5205_wasm_write -Wl,--export=msm5205_wasm_gain \
  -Wl,--export=msm5205_wasm_mute -Wl,--export=msm5205_wasm_render \
  -Wl,--export=msm5205_wasm_read \
  -o "$OUT_DIR/msm5205_wasm.wasm"
cat > "$OUT_DIR/msm5205_wasm.js" <<'EOF'
// Generated by scripts/build_msm5205_wasm.sh; SPDX-License-Identifier: BSD-3-Clause
// Copyright (c) 2026, kyorohiro.
export const MSM5205_PCM_ABI = 1;
const moduleURL = import.meta.url.replace(/[?#].*$/, '');
export const MSM5205_WASM_URL = moduleURL.slice(0, moduleURL.lastIndexOf('/') + 1) + 'msm5205_wasm.wasm';
EOF
