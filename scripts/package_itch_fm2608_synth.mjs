const record = bytes => ({bytes:bytes.length, sha256:createHash('sha256').update(bytes).digest('hex')});

async function filesIn(base, prefix = '') {
  const files = [];
  for (const entry of await readdir(join(base, prefix), {withFileTypes:true})) {
    const path = prefix + entry.name;
    if (entry.isDirectory()) files.push(...await filesIn(base, path + '/'));
    else {
      assert(entry.isFile(), `Unsupported archive entry: ${path}`);
      files.push(path);
    }
  }
  return files.sort();
}

function zip(base, target, names) {
  execFileSync('python3', ['-c', String.raw`
import json,sys,zipfile
from pathlib import Path
base=Path(sys.argv[1]); names=json.load(sys.stdin)
with zipfile.ZipFile(sys.argv[2],'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
 for name in names:
  info=zipfile.ZipInfo(name,(1980,1,1,0,0,0));info.create_system=3;info.external_attr=0o100644<<16
  z.writestr(info,(base/name).read_bytes(),compress_type=zipfile.ZIP_DEFLATED,compresslevel=9)
with zipfile.ZipFile(sys.argv[2]) as z: assert z.testzip() is None
`, base, target], {input:JSON.stringify(names)});
}

export function validateFm2608SynthVersion(value) {
  if (typeof value !== 'string' || !/^[A-Za-z0-9][A-Za-z0-9._+-]{0,79}$/.test(value)) {
    throw new Error('Invalid package version');
  }
  return value;
}

/** Verify the exact source and generated bytes retained in the native kit. */
export async function verifyFm2608SourceReceipt(stage, receipt) {
  assert(receipt?.schemaVersion === 1 && receipt.component === 'ym2608'
    && Array.isArray(receipt.inputs) && receipt.inputs.length, 'Expected YM2608 source receipt');
  const required = new Set([
    'sources/ym2608-sdk/wasm/ym2608_wasm.cpp',
    'sources/ym2608-sdk/wasm/ymfm_wasm_interface.h',
    'sources/ym2608-sdk/scripts/build_ym2608_wasm.sh',
    'sources/ym2608-sdk/vendor/ymfm/ymfm_opn.cpp',
    'sources/ym2608-sdk/vendor/ymfm/ymfm_ssg.cpp',
    'sources/ym2608-sdk/vendor/ymfm/ymfm_adpcm.cpp',
    'sources/ym2608-sdk/vendor/ymfm/LICENSE',
  ]);
  const verify = async (path, expected) => {
    assert(typeof path === 'string' && path && !path.startsWith('/') && !path.includes('\\')
      && path.split('/').every(part => part && part !== '.' && part !== '..'), 'Unsafe source receipt path');
    const actual = record(await readFile(join(stage, path)));
    assert(actual.bytes === expected?.bytes && actual.sha256 === expected.sha256,
      `YM2608 source receipt mismatch: ${path}`);
  };
  const seen = new Set();
  for (const entry of receipt.inputs) {
    assert(!seen.has(entry.path), 'Duplicate source receipt path');
    seen.add(entry.path);
    await verify(entry.path, entry);
    required.delete(entry.path);
  }
  assert(!required.size, 'Incomplete YM2608 native source receipt');
  for (const name of ['ym2608_wasm.js', 'ym2608_wasm.wasm']) {
    await verify('generated/' + name, receipt.generated?.[name]);
  }
}

async function copyNativeSources(stage) {
  const sdkRoot = join(root, 'third_party/tetorica-soundchip-native');
  const pinBytes = await readFile(join(root, 'third_party/soundchip-sdk.json'));
  const pin = JSON.parse(pinBytes);
  const manifestBytes = await readFile(join(sdkRoot, 'RELEASE-MANIFEST.json'));
  assert.equal(record(manifestBytes).sha256, pin.manifestSha256, 'YM2608 SDK manifest hash differs');
  const manifest = JSON.parse(manifestBytes);
  const artifacts = await getRuntimeArtifactManifest({root});
  const artifact = artifacts.artifacts.find(item => item.id === 'ym2608');
  const build = JSON.parse(await readFile(join(root, 'tetorica_src/runtime/generated/build-info.json')))
    .artifacts.find(item => item.id === 'ym2608');
  assert(artifact && build, 'YM2608 build provenance is missing');
  const relative = path => path.replace(/^third_party\/tetorica-soundchip-native\//, '');
  const names = [...new Set([
    ...artifact.sourceFiles.map(relative), ...artifact.licenseFiles.map(relative),
    'sdk.json', 'catalog/source_inventory.json',
  ])].sort();
  const inputs = [];
  const sourceInputs = [];
  // The fixed SDK paths are retained so its build recipe runs as authored.
  for (const name of names) {
    const bytes = await readFile(join(sdkRoot, name));
    const actual = record(bytes), expected = manifest.files[name];
    assert(expected && actual.bytes === expected.size && actual.sha256 === expected.sha256,
      `YM2608 SDK source mismatch: ${name}`);
    const compiled = build.sourceFiles.find(item => item.path === name);
    if (compiled) assert(actual.bytes === compiled.size && actual.sha256 === compiled.sha256,
      `YM2608 compiled source mismatch: ${name}`);
    const path = 'sources/ym2608-sdk/' + name;
    await mkdir(dirname(join(stage, path)), {recursive:true});
    await writeFile(join(stage, path), bytes);
    inputs.push({path, ...actual});
    sourceInputs.push('third_party/tetorica-soundchip-native/' + name);
  }
  for (const [path, bytes] of [
    ['sources/ym2608-sdk/RELEASE-MANIFEST.json', manifestBytes],
    ['sources/ym2608-sdk/soundchip-sdk.json', pinBytes],
  ]) {
    await writeFile(join(stage, path), bytes);
    inputs.push({path, ...record(bytes)});
  }
  await mkdir(join(stage, 'licenses/ymfm'), {recursive:true});
  await copyFile(join(sdkRoot, 'vendor/ymfm/LICENSE'), join(stage, 'licenses/ymfm/LICENSE'));
  const generated = {};
  for (const name of ['ym2608_wasm.js', 'ym2608_wasm.wasm']) {
    const bytes = await readFile(join(stage, 'generated', name));
    generated[name] = record(bytes);
    const expected = build.outputs.find(item => item.path === name);
    assert(expected && generated[name].bytes === expected.size && generated[name].sha256 === expected.sha256,
      `YM2608 generated output mismatch: ${name}`);
  }
  const receipt = {schemaVersion:1, component:'ym2608', sdk:pin, build, inputs, generated};
  await verifyFm2608SourceReceipt(stage, receipt);
  await writeFile(join(stage, 'sources/YM2608.json'), JSON.stringify(receipt, null, 2) + '\n');
  await writeFile(join(stage, 'sources/YM2608.md'), `# YM2608 / OPNA source and rebuilding

The complete ymfm core, YM2608 bridge, original build recipes and licenses are
included under [ym2608-sdk/](ym2608-sdk/). Their paths and bytes match the fixed
tetorica-soundchip-native SDK. [YM2608.json](YM2608.json) records the SDK pin,
compiled input hashes and the distributed JavaScript loader and WASM hashes.

From this sources directory, with Emscripten installed, run:

\`\`\`sh
sh ym2608-sdk/scripts/build_ym2608_wasm.sh "$(pwd)/../generated"
\`\`\`

The recipe accepts an absolute output directory. Its build uses the included
ymfm files and WASM bridge. Keyboard allocation, Pitch, Files, audio decoding
and scheduling are implemented in the browser host.

The default six-voice rhythm data is the original Tetorica synthetic ROM.
Its source, license and generator are under
[assets/opna-rhythm/](../assets/opna-rhythm/README.md).
`);
  return {inputs:inputs.length, sdkVersion:pin.version, sourceInputs};
}

async function copyCodeEffects(stage, inputs) {
  const source = 'tetorica_src/runtime/generated/effects/gain.wasm';
  await copyFile(join(root, source), join(stage, 'js/native_audio_effect.wasm'));
  inputs.add(source);
  const kit = 'sources/code-effects';
  await mkdir(join(stage, kit, 'scripts'), {recursive:true});
  await mkdir(join(stage, kit, 'tetorica_src/native'), {recursive:true});
  await cp(join(root, 'tetorica_src/native/audio_effect'), join(stage, kit, 'tetorica_src/native/audio_effect'), {recursive:true});
  await copyFile(join(root, 'scripts/build_native_audio_effect.sh'), join(stage, kit, 'scripts/build_native_audio_effect.sh'));
  await copyFile(join(root, 'LICENSE'), join(stage, kit, 'LICENSE'));
  for (const name of await filesIn(join(root, 'tetorica_src/native/audio_effect'))) {
    inputs.add('tetorica_src/native/audio_effect/' + name);
  }
  inputs.add('scripts/build_native_audio_effect.sh');
  await writeFile(join(stage, kit, 'README.md'), `# Code software effects

The original Tetorica effect rack uses BSD-3-Clause and is applied after the
YM2608. The browser implementation is js/native_fx_rack.js and its binary is
js/native_audio_effect.wasm. Rebuild from this directory with Emscripten:

\`\`\`sh
sh scripts/build_native_audio_effect.sh /tmp/tetorica-fm2608-effects
cp /tmp/tetorica-fm2608-effects/gain.wasm ../../js/native_audio_effect.wasm
\`\`\`
`);
}

export async function packageFm2608Synth({version = 'dev', releaseDir = join(root, 'release')} = {}) {
  validateFm2608SynthVersion(version);
  await checkRuntimeArtifacts({root, ids:['ym2608', 'native_audio_effect'], mirrors:true});
  releaseDir = resolve(releaseDir);
  await mkdir(releaseDir, {recursive:true});
  const archive = join(releaseDir, `tetorica_fm2608_synth_${version}_itch.zip`);
  try {
    await readFile(archive);
    throw new Error(`Archive already exists: ${archive}`);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  const stage = await mkdtemp(join(releaseDir, `itch_fm2608_synth_${version}-`));
  const browser = await copyReadableModules({root, stage,
    entries:['docs/synth-fm2608/synth.js', 'docs/synth-fm2608/synth.css',
      'docs/synth-fm2608/audio_worklet.js', 'docs/js/native-fx-worklet.js'],
    factories:['docs/generated/ym2608_wasm.js'],
  });
  const inputs = new Set(browser.inputs);
  for (const name of ['tetorica-playground-globals.d.ts', 'tetorica-playground-ym2608.d.ts', 'tetorica-shell.d.ts']) {
    const source = 'docs/playground/' + name;
    await mkdir(join(stage, 'playground'), {recursive:true});
    await copyFile(join(root, source), join(stage, 'playground', name));
    inputs.add(source);
  }
  for (const [source, destination] of [
    ['docs/playground/vendor/fflate-LICENSE', 'playground/vendor/fflate-LICENSE'],
    ['packages/virtual-files/LICENSE', 'licenses/tetorica-virtual-files/LICENSE'],
  ]) {
    await mkdir(dirname(join(stage, destination)), {recursive:true});
    await copyFile(join(root, source), join(stage, destination));
    inputs.add(source);
  }
  await copyCodeEffects(stage, inputs);
  await copyRuntimeArtifacts({root, destination:join(stage, 'generated'), ids:['ym2608'], includeMetadata:false});
  await copyOpnaRhythm(stage);
  for (const name of ['LICENSE', 'README.md', 'generate.mjs', 'synthesis.mjs']) inputs.add('assets/opna-rhythm/' + name);
  inputs.add('tetorica_src/runtime/tetorica_ym2608_adpcm_rom.bin');
  const native = await copyNativeSources(stage);
  for (const name of native.sourceInputs) inputs.add(name);
  inputs.add('third_party/tetorica-soundchip-native/RELEASE-MANIFEST.json');
  inputs.add('third_party/soundchip-sdk.json');
  const home = 'https://kyorohiro.github.io/hello_ymfm_wasm/';
  let html = await readFile(join(root, 'docs/synth-fm2608/index.html'), 'utf8');
  html = html.replace(/href="(\.\.\/[^"#]+)"/g, (match, path) => {
    if (path === '../' + icon) return match;
    if (path === '../js/ym2608synth.js') return 'href="https://github.com/kyorohiro/hello_ymfm_wasm/blob/main/tetorica_src/runtime/ym2608synth.js"';
    return `href="${new URL(path, home + 'synth-fm2608/').href}"`;
  });
  await writeFile(join(stage, 'synth-fm2608/index.html'), html);
  await writeFile(join(stage, 'index.html'), html
    .replace(/\b(href|src)="\.\/(synth\.(?:css|js))([?#][^"]*)?"/g, '$1="./synth-fm2608/$2$3"')
    .replaceAll('../' + icon, './' + icon));
  await copyFile(join(root, 'docs', icon), join(stage, icon));
  await copyFile(join(root, 'LICENSE'), join(stage, 'LICENSE'));
  const guide = (await readFile(join(root, 'docs/synth-fm2608/README.md'), 'utf8'))
    .replace(/\]\(([^)]+)\)/g, (match, target) => {
      if (/^(?:https?:|#)/.test(target) || target === 'index.html') return match;
      return `](${new URL(target, 'https://github.com/kyorohiro/hello_ymfm_wasm/blob/main/docs/synth-fm2608/').href})`;
    });
  await writeFile(join(stage, 'synth-fm2608/README.md'), guide);
  await writeFile(join(stage, 'README.md'), guide + '\n## Included sources\n\nSee [YM2608 source and rebuilding](sources/YM2608.md), [native source receipt](sources/YM2608.json), [rhythm source and license](assets/opna-rhythm/README.md), [browser inputs](sources/fm2608-synth-browser-inputs.zip) and their [hash receipt](sources/fm2608-synth-browser.json).\n');
  for (const path of ['docs/synth-fm2608/index.html', 'docs/synth-fm2608/README.md', 'docs/' + icon,
    'LICENSE', 'package.json', 'package-lock.json', 'scripts/package_itch_fm2608_synth.mjs',
    'scripts/package_itch_fm2608_synth.sh', 'scripts/copy_opna_rhythm.mjs', 'scripts/copy_readable_modules.mjs',
    'scripts/runtime_artifacts.mjs', 'scripts/wasm_sdk_inventory.mjs',
    'tetorica_src/runtime/generated/ym2608_wasm.js']) inputs.add(path);
  const names = [...inputs].sort(), sourceArchive = 'sources/fm2608-synth-browser-inputs.zip';
  zip(root, join(stage, sourceArchive), names);
  const receipt = {
    schemaVersion:1, product:'Tetorica FM2608 Synth', productId:'tetorica-fm2608-synth', version,
    builder:{name:'source-copy', minify:false, bundle:false, dependencyAnalyzer:{name:'esbuild', version:esbuildVersion}},
    bundles:browser.entries, modules:browser.modules,
    sourceCheck:{inputs:native.inputs, sdkVersion:native.sdkVersion},
    originalInputs:await Promise.all(names.map(async path => ({path, ...record(await readFile(join(root, path)))}))),
    sourceArchive:{path:sourceArchive, ...record(await readFile(join(stage, sourceArchive)))},
  };
  await writeFile(join(stage, 'sources/fm2608-synth-browser.json'), JSON.stringify(receipt, null, 2) + '\n');
  const namesInStage = await filesIn(stage);
  assert(namesInStage.length <= 1000, 'itch.io file limit exceeded');
  const temporary = stage + '.zip';
  try {
    zip(stage, temporary, namesInStage);
    await copyFile(temporary, archive, constants.COPYFILE_EXCL);
    await rm(temporary);
  } catch (error) {
    await rm(temporary, {force:true});
    throw error;
  }
  return {passed:true, stage, archive, files:namesInStage.length, bundles:browser.entries.length,
    archiveRecord:record(await readFile(archive)), sourceCheck:receipt.sourceCheck};
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length > 3) throw new Error('Usage: node scripts/package_itch_fm2608_synth.mjs [VERSION]');
  console.log(JSON.stringify(await packageFm2608Synth({version:process.argv[2] ?? 'dev'}), null, 2));
}
