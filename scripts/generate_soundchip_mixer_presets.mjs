import {createHash} from 'node:crypto';
import {dirname,resolve} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {buildPlaygroundMixerDefaults,MIXER_LISTENING_LEVELS} from './generate_playground_mixer_defaults.mjs';
import {validatePs1MixerCalibration,validatePs1MixerCalibrationSources} from './ps1_mixer_calibration.mjs';
import {validateWonderSwanMixerCalibration,validateWonderSwanMixerCalibrationSources} from './wonderswan_mixer_calibration.mjs';
import {validatePokeyMixerCalibration,validatePokeyMixerCalibrationSources} from './pokey_mixer_calibration.mjs';

const defaultPsgReportPath = fileURLToPath(new URL('../docs/issues/soundchip_psg_levels_04.json',import.meta.url));

/** Retain the measured output units, then balance standalone square-wave sources. */
export function buildSoundChipMixerPresets(report, psgReport, ps1Report=undefined, wonderswanReport=undefined, pokeyReport=undefined) {
  const {factoryDefaults,factoryEngines} = buildPlaygroundMixerDefaults(report);
  const names=['segapsg','ay8910','nes'],reference=psgReport?.reference;
  const anchor=factoryDefaults.kinds.find(record=>record.name==='ym2608').volume;
  if(psgReport?.schemaVersion!==1||psgReport.passed!==true||psgReport.sampleRate!==44100||
    psgReport.referenceFrequencyHz!==440||reference?.id!=='ym2608'||reference.gain!==anchor||
    !Number.isFinite(reference.unityAcRms)||reference.unityAcRms<=0||
    !Number.isFinite(reference.targetAcRms)||reference.targetAcRms<=0||
    Math.abs(reference.targetAcRms/(reference.unityAcRms*anchor)-1)>1e-6||
    JSON.stringify(Object.keys(psgReport.defaults??{}).sort())!==JSON.stringify([...names].sort())) {
    throw new Error('Invalid sound-chip PSG balance report');
  }
  for(const name of names) {
    for(const frequencyHz of [220,440,880]) {
      const rows=psgReport.rows?.filter(row=>row.kind===name&&row.frequencyHz===frequencyHz&&row.canonical===true);
      if(rows?.length!==1||rows[0].sampleRate!==44100||rows[0].backend!=='wasm'||
        !Number.isFinite(rows[0].rawAcRms)||rows[0].rawAcRms<=0) {
        throw new Error('Missing sound-chip PSG reference: '+name+'/'+frequencyHz);
      }
    }
    const row=psgReport.rows.find(row=>row.kind===name&&row.frequencyHz===440&&row.canonical===true);
    const entry=factoryDefaults.kinds.find(record=>record.name===name),gain=psgReport.defaults[name];
    if(!Number.isFinite(gain)||gain<=0||gain>=entry.volume||gain>2||
      gain!==Number((reference.targetAcRms/row.rawAcRms).toFixed(6))) {
      throw new Error('Invalid sound-chip PSG gain: '+name);
    }
    entry.volume=gain;
  }
  // Validate the historical measurements before applying the listening policy.
  for(const entry of factoryDefaults.kinds) {
    if(Object.hasOwn(MIXER_LISTENING_LEVELS,entry.name))entry.volume=MIXER_LISTENING_LEVELS[entry.name];
  }
  if(ps1Report!==undefined) {
    const ps1=validatePs1MixerCalibration(report,ps1Report);
    factoryDefaults.kinds.push({name:'ps1',volume:ps1.extraVolume});
  }
  if(wonderswanReport!==undefined) {
    const wonderswan=validateWonderSwanMixerCalibration(report,wonderswanReport);
    factoryDefaults.kinds.push({name:'wonderswan',volume:wonderswan.extraVolume});
  }
  if(pokeyReport!==undefined) {
    const pokey=validatePokeyMixerCalibration(report,pokeyReport);
    factoryDefaults.kinds.push({name:'pokey',volume:pokey.extraVolume});
  }
  return {calibrated:{gainUnits:'source',factoryDefaults,factoryEngines}};
}

/** Machine-specific trims stay in Playground; user-authored settings remain absolute. */
export function renderSoundChipMixerPresets(report, psgReport, ps1Report=undefined, wonderswanReport=undefined, pokeyReport=undefined) {
  const presets=buildSoundChipMixerPresets(report,psgReport,ps1Report,wonderswanReport,pokeyReport);
  return `// Generated by scripts/generate_soundchip_mixer_presets.mjs; do not edit gains here.
// Opt-in measured output units with the shared PSG/wavetable listening balance.
// Endpoint gain, timbre, polyphony and raw generateStereo() output are unchanged.

/** @template T @param {T} value @returns {T} */
const freeze = value => {
  if(value&&typeof value==='object') {for(const child of Object.values(value))freeze(child);Object.freeze(value);}
  return value;
};

export const SOUNDCHIP_MIXER_LISTENING_LEVELS = freeze(${JSON.stringify(MIXER_LISTENING_LEVELS,null,2)});

/** Optional factory policies for new SoundChipMixer().
 * calibrated covers measured standalone-chip routes; other kinds retain their usual defaults.
 * Explicit common and per-ID settings override these fallback values.
 * @type {{readonly calibrated: import('./soundchip_mixer.js').SoundChipMixerOptions}}
 */
export const SOUNDCHIP_MIXER_PRESETS = freeze(${JSON.stringify(presets,null,2)});
`;
}

export async function generateSoundChipMixerPresets({reportPath,psgReportPath=defaultPsgReportPath,ps1ReportPath,wonderswanReportPath,pokeyReportPath,outPath,check=false}) {
  const source = JSON.parse(await readFile(reportPath,'utf8'));
  const psgReport=JSON.parse(await readFile(psgReportPath,'utf8'));
  const ps1Report=ps1ReportPath===undefined?undefined:JSON.parse(await readFile(ps1ReportPath,'utf8'));
  const wonderswanReport=wonderswanReportPath===undefined?undefined:JSON.parse(await readFile(wonderswanReportPath,'utf8'));
  const pokeyReport=pokeyReportPath===undefined?undefined:JSON.parse(await readFile(pokeyReportPath,'utf8'));
  const output = renderSoundChipMixerPresets(source,psgReport,ps1Report,wonderswanReport,pokeyReport);
  const sources=Object.entries(psgReport.sources??{});
  if(!sources.length)throw new Error('Missing sound-chip PSG source hashes');
  for(const [path,sha256] of sources) {
    const bytes=await readFile(new URL('../'+path,import.meta.url));
    if(createHash('sha256').update(bytes).digest('hex')!==sha256)throw new Error('Sound-chip PSG source changed; remeasure: '+path);
  }
  if(ps1Report!==undefined)await validatePs1MixerCalibrationSources({reportPath,ps1Report});
  if(wonderswanReport!==undefined)await validateWonderSwanMixerCalibrationSources({reportPath,wsReport:wonderswanReport});
  if(pokeyReport!==undefined)await validatePokeyMixerCalibrationSources({reportPath,pokeyReport});
  if(check) {
    if(await readFile(outPath,'utf8')!==output)throw new Error(`Generated sound-chip Mixer presets are stale: ${outPath}`);
  }else {
    await mkdir(dirname(outPath),{recursive:true});
    await writeFile(outPath,output);
  }
}

async function main(args) {
  const options = {
    reportPath:fileURLToPath(new URL('../docs/issues/playground_chip_levels_01.json',import.meta.url)),
    ps1ReportPath:fileURLToPath(new URL('../docs/issues/ps1_chip_levels_deferred_release_01.json',import.meta.url)),
    wonderswanReportPath:fileURLToPath(new URL('../docs/issues/wonderswan_chip_levels_deferred_release_01.json',import.meta.url)),
    pokeyReportPath:fileURLToPath(new URL('../docs/issues/pokey_chip_levels_deferred_release_01.json',import.meta.url)),
    outPath:fileURLToPath(new URL('../web/soundchip_mixer_presets.js',import.meta.url)),
  };
  let noPs1=false,explicitPs1=false,noWonderSwan=false,explicitWonderSwan=false,noPokey=false,explicitPokey=false;
  for(let index=0;index<args.length;index++) {
    const arg = args[index];
    if(arg==='--help') {
      console.log('Usage: node scripts/generate_soundchip_mixer_presets.mjs [--report=<baseline.json>] [--psg-report=<balance.json>] [--ps1-report=<extension.json> | --no-ps1] [--wonderswan-report=<extension.json> | --no-wonderswan] [--pokey-report=<extension.json> | --no-pokey] [--out=<module.js>] [--check]');
      return;
    }
    if(arg==='--check') {options.check=true;continue;}
    if(arg==='--no-ps1') {noPs1=true;continue;}
    if(arg==='--no-wonderswan') {noWonderSwan=true;continue;}
    if(arg==='--no-pokey') {noPokey=true;continue;}
    const match = /^(--report|--psg-report|--ps1-report|--wonderswan-report|--pokey-report|--out)(?:=(.*))?$/.exec(arg);
    if(!match)throw new Error(`Unknown argument: ${arg}`);
    const value = match[2]??args[++index];
    if(!value||value.startsWith('--'))throw new Error(`Missing value for ${match[1]}`);
    options[match[1]==='--report'?'reportPath':match[1]==='--psg-report'?'psgReportPath':match[1]==='--ps1-report'?'ps1ReportPath':match[1]==='--wonderswan-report'?'wonderswanReportPath':match[1]==='--pokey-report'?'pokeyReportPath':'outPath']=resolve(value);
    if(match[1]==='--ps1-report')explicitPs1=true;
    if(match[1]==='--wonderswan-report')explicitWonderSwan=true;
    if(match[1]==='--pokey-report')explicitPokey=true;
  }
  if(noPs1&&explicitPs1)throw new Error('--no-ps1 cannot be combined with --ps1-report');
  if(noPs1)delete options.ps1ReportPath;
  if(noWonderSwan&&explicitWonderSwan)throw new Error('--no-wonderswan cannot be combined with --wonderswan-report');
  if(noWonderSwan)delete options.wonderswanReportPath;
  if(noPokey&&explicitPokey)throw new Error('--no-pokey cannot be combined with --pokey-report');
  if(noPokey)delete options.pokeyReportPath;
  await generateSoundChipMixerPresets(options);
  console.log(`${options.check?'CHECK PASS':'Generated'}: ${options.outPath}`);
}
if(process.argv[1]&&pathToFileURL(resolve(process.argv[1])).href===import.meta.url) {
  main(process.argv.slice(2)).catch(error=>{console.error(error.message);process.exitCode=1;});
}
