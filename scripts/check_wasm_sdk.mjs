export function parseWasmSdkArguments(argv) {
  if(argv.includes('--help')){assert.deepEqual(argv,['--help'],'--help must stand alone');return {help:true};}
  const options={};
  for(let i=0;i<argv.length;i++){
    const arg=argv[i],at=arg.indexOf('='),name=at<0?arg:arg.slice(0,at);
    assert(['--work-dir','--reference-dir','--sdk-dir'].includes(name),`Unknown argument: ${arg}\n${usage}`);
    assert(!Object.hasOwn(options,name),'Duplicate argument: '+name);
    const value=at<0?argv[++i]:arg.slice(at+1);assert(value&&!value.startsWith('--'),name+' needs a value');
    options[name]=resolve(value);
  }
  return options;
}

async function canonicalLocation(path) {
  try{return await realpath(path);}catch(error){if(error.code!=='ENOENT')throw error;return join(await canonicalLocation(dirname(path)),basename(path));}
}
async function metadata(path) {const data=await readFile(path);return {path,bytes:data.length,sha256:sha(data)};}
async function snapshotInputs(inventory) {
  const paths=new Set([join(root,'package.json'),join(root,'third_party/soundchip-sdk.json')]);
  async function walk(directory,all=false) {
    for(const entry of await readdir(directory,{withFileTypes:true})){
      const path=join(directory,entry.name);
      assert(!entry.isSymbolicLink(),'Validation input must not be a symlink: '+path);
      if(entry.isDirectory())await walk(path,all);
      else if(entry.isFile()&&(all||/\.(?:js|mjs|json|wasm|ts|sh|py)$/.test(entry.name)))paths.add(path);
    }
  }
  for(const dir of ['scripts','web','docs/js','docs/generated','docs/vgm_analyzer','docs/playground'])await walk(join(root,dir));
  await walk(inventory.sdkRoot,true);
  return Promise.all([...paths].sort().map(metadata));
}
async function verifySnapshot(snapshot,inventory) {
  assert.deepEqual(await snapshotInputs(inventory),snapshot,'Repository runtime, build recipes or SDK changed during validation');
}
async function copyBuild(source,target,inventory) {
  await mkdir(target);
  for(const name of ['build-info.json',...inventory.builds.flatMap(a=>a.outputs)]) {
    await copyFile(join(source,name),join(target,name),constants.COPYFILE_EXCL);
  }
  // The generated pairs are ES modules even outside the repository's scope.
  await writeFile(join(target,'package.json'),serialize({type:'module'}),{flag:'wx'});
}
export async function runWasmSdkCommand(command,args,logPath,timeoutMs) {
  const started=Date.now(),log=await open(logPath,'wx');
  try {
    await new Promise((resolveRun,reject)=>{
      const grouped=process.platform!=='win32';
      const child=spawn(command,args,{cwd:root,env:process.env,detached:grouped,stdio:['ignore',log.fd,log.fd]});
      let timedOut=false,finished=false,forceTimer;
      const finish=error=>{if(finished)return;finished=true;clearTimeout(timer);clearTimeout(forceTimer);if(error)reject(error);else resolveRun();};
      const kill=signal=>{if(!child.pid)return;try{if(grouped)process.kill(-child.pid,signal);else child.kill(signal);}catch(error){if(error.code!=='ESRCH')finish(error);}};
      const timer=setTimeout(()=>{
        timedOut=true;kill('SIGTERM');
        // A shell can exit before a compiler descendant; stop the entire POSIX
        // process group before closing its log or returning a failed run.
        forceTimer=setTimeout(()=>{kill('SIGKILL');finish(new Error(`${command} failed (timeout); see ${logPath}`));},2000);
      },timeoutMs);
      child.once('error',finish);
      child.once('close',(code,signal)=>{if(!timedOut)finish(code===0?null:new Error(`${command} failed (${signal??'exit '+code}); see ${logPath}`));});
    });
  } finally {await log.close();}
  return {command,args,seconds:(Date.now()-started)/1000,log:await metadata(logPath),exitCode:0};
}
export function compareWasmSdkAbi(reference,candidate) {
  const ordered=entries=>entries.toSorted((a,b)=>JSON.stringify(a).localeCompare(JSON.stringify(b)));
  const referenceBuilds=[...reference.artifacts,...reference.applicationAudio,...(reference.instruments??[])];
  const candidateBuilds=[...candidate.artifacts,...candidate.applicationAudio,...(candidate.instruments??[])];
  assert.deepEqual(candidateBuilds.map(a=>a.id),referenceBuilds.map(a=>a.id));
  for(let i=0;i<referenceBuilds.length;i++){
    const a=referenceBuilds[i],b=candidateBuilds[i];
    assert.deepEqual(ordered(b.wasm.exports),ordered(a.wasm.exports),a.id+': WASM export ABI changed');
    assert.deepEqual(ordered(b.wasm.imports),ordered(a.wasm.imports),a.id+': WASM import ABI changed');
  }
}

async function checkApplicationAudio(inventory, candidate, reference, workDirectory) {
  if (!inventory.applicationAudio.length) return null;
  assert.deepEqual(candidate.applicationAudio.map(a=>a.id), ['cdda','msm5205']);
  const byteComparisons=[];
  for (const artifact of candidate.applicationAudio) {
    const baseline=reference.applicationAudio.find(a=>a.id===artifact.id);
    assert(baseline,`Missing deployed ${artifact.id} reference.`);
    assert.deepEqual(artifact.outputs,baseline.outputs,`${artifact.id}: generated JS/WASM bytes changed`);
    byteComparisons.push({id:artifact.id,outputs:artifact.outputs,byteIdentical:true});
  }
  const commands=[];
  for (const [name, script, args] of [
    ['application-audio-smoke','application_audio_wasm_smoke.mjs',[candidate.directory]],
    ['application-audio-parity','check_application_audio_core.mjs',
      ['--wasm-dir',candidate.directory,'--artifact','all']],
  ]) {
    const logPath=join(workDirectory,'logs',name+'.log');
    const command=await runWasmSdkCommand(process.execPath,
      [join(inventory.sdkRoot,'tests',script),...args],logPath,5*60*1000);
    const report=JSON.parse(await readFile(logPath,'utf8'));
    assert.equal(report.status,'PASS',name+': comparison failed');
    assert.deepEqual(report.results.map(a=>a.artifact),['cdda','msm5205'],name+': missing audio modules');
    if (name.endsWith('parity')) {
      assert.equal(report.standaloneSDK,true);
      for (const result of report.results) {
        assert.equal(result.status,'PASS');assert.equal(result.c11,true);assert.equal(result.cpp14,true);
        assert(result.results.length>0 && result.results.every(c=>c.nativeWasmExact));
      }
    }
    commands.push({name,command,report});
  }
  return {passed:true,byteComparisons,checks:commands};
}
export function validatePs1SpuSdkReport(report) {
  assert.equal(report.passed,true,'PS1 SPU actual-core smoke failed');
  assert.equal(report.artifact,'ps1_spu');assert.equal(report.sampleRate,44100);
  assert.equal(report.voices,24);assert.equal(report.ramBytes,524288);
  assert(Number.isSafeInteger(report.renderedFrames)&&report.renderedFrames>0,'PS1 rendered frames');
  for(const check of ['fixed-rate-C-ABI-register-RAM-and-render-guards',
    '24-voices-high-key-bank-ADSR-release-and-stereo',
    'exact-block-partition-and-independent-instance-state',
    'preset-reverb-tail-reset-and-retained-sample-RAM',
    'actual-Native-WASM-24-voice-ADSR-and-reverb-parity'])assert(report.checks?.includes(check),'Missing PS1 check: '+check);
  const parity=report.nativeParity;
  assert.equal(parity?.passed,true,'PS1 Native parity must run');
  assert(Number.isSafeInteger(parity.interleavedSamples)&&parity.interleavedSamples>0,'Nonempty PS1 Native comparisons');
  assert.equal(parity.tolerance,1e-6,'PS1 Native parity tolerance');
  assert(Number.isFinite(parity.maxAbsoluteError)&&parity.maxAbsoluteError>=0&&parity.maxAbsoluteError<=parity.tolerance,'PS1 Native PCM difference');
  return report;
}

async function checkPs1Instrument(inventory,candidate,reference,workDirectory) {
  if(!(inventory.instruments??[]).length)return null;
  const artifact=candidate.instruments.find(a=>a.id==='ps1_spu'),baseline=reference.instruments?.find(a=>a.id==='ps1_spu');
  assert(artifact,'Missing candidate PS1 SPU');
  assert(baseline,'Missing deployed PS1 SPU reference');
  assert.deepEqual(artifact.outputs,baseline.outputs,'ps1_spu: generated JS/WASM bytes changed');
  const buildDirectory=join(workDirectory,'ps1-native'),commands=[];
  for(const [name,command,args] of [
    ['ps1-native-configure','cmake',['-S',inventory.sdkRoot,'-B',buildDirectory,
      '-DCMAKE_BUILD_TYPE=Release','-DTETORICA_NATIVE_BUILD_EXAMPLES=OFF','-DTETORICA_NATIVE_BUILD_TESTS=ON']],
    ['ps1-native-build','cmake',['--build',buildDirectory,'--config','Release','--target','tetorica_ps1_spu_fixture','--parallel','2']],
    ['ps1-native-query','ctest',['--test-dir',buildDirectory,'-C','Release','--show-only=json-v1','-R','^tetorica.ps1_spu.self_test$']],
  ])commands.push({name,...await runWasmSdkCommand(command,args,join(workDirectory,'logs',name+'.log'),5*60*1000)});
  // Ask CTest for the generated executable instead of assuming a single- or
  // multi-configuration platform path, suffix or build-system layout.
  const query=JSON.parse(await readFile(join(workDirectory,'logs/ps1-native-query.log'),'utf8'));
  assert.equal(query.kind,'ctestInfo');assert.equal(query.tests?.length,1);
  assert.equal(query.tests[0].name,'tetorica.ps1_spu.self_test');
  const [fixture,...fixtureArgs]=query.tests[0].command??[];
  assert(typeof fixture==='string'&&isAbsolute(fixture)&&inside(fixture,buildDirectory),'PS1 fixture must stay in the isolated build');
  assert((await lstat(fixture)).isFile(),'PS1 Native fixture was not built');
  assert.deepEqual(fixtureArgs,['--self-test']);
  const nativeCommand=await runWasmSdkCommand(fixture,fixtureArgs,join(workDirectory,'logs/ps1-native-fixture.log'),120000);
  const nativeReport=JSON.parse(await readFile(join(workDirectory,'logs/ps1-native-fixture.log'),'utf8'));
  assert.equal(nativeReport.status,'pass');commands.push({name:'ps1-native-fixture',...nativeCommand});
  const script=join(inventory.sdkRoot,'tests/ps1_spu_wasm_smoke.mjs');
  const command=await runWasmSdkCommand(process.execPath,[script,candidate.directory,fixture],join(workDirectory,'logs/ps1-instrument.log'),5*60*1000);
  const report=validatePs1SpuSdkReport(JSON.parse(await readFile(join(workDirectory,'logs/ps1-instrument.log'),'utf8')));
  return {passed:true,byteComparisons:[{id:'ps1_spu',outputs:artifact.outputs,byteIdentical:true}],
    nativeBuild:{directory:buildDirectory,fixture:await metadata(fixture),commands,report:nativeReport},
    checker:await metadata(script),command,report};
}

