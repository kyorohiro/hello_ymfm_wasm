// Expand the verified public-API references into an editable, standalone example.
// The generated Playground source never imports or evaluates calibration code.
import {readFile, writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {FM_CALIBRATION_KINDS, buildFmCalibrationReference} from './soundchip_calibration_fm.mjs';
import {PCM_CALIBRATION_KINDS, buildPcmCalibrationReference} from './soundchip_calibration_pcm.mjs';

export const CHIP_COMPARISON_KINDS = Object.freeze([...FM_CALIBRATION_KINDS, ...PCM_CALIBRATION_KINDS]);
export const CHIP_COMPARISON_TARGET = new URL('../docs/playground/examples/genesis/chip-level-comparison.js', import.meta.url);

function standaloneReference(reference) {
  const prefix = reference.setup.match(/^const\s+(source|chip)\s*=\s*await createSoundChip\((['"])([^'"]+)\2,\s*\{\s*id\s*:\s*(['"])calibration-source\4\s*\}\);\s*context\.calibrationSource\s*=\s*\1;\s*/);
  if (!prefix || prefix[3] !== reference.kind) throw new Error(`Unexpected reference source prefix: ${reference.kind}`);
  const local = prefix[1];
  const setup = reference.setup.slice(prefix[0].length).trimEnd();
  const stop = reference.stop.replace(/\bcontext\.calibrationSource\b/g, local).trimEnd();
  if (/\bcontext\b|\bcreateSoundChip\b|calibration-source/.test(`${setup}\n${stop}`)) {
    throw new Error(`Reference leaks calibration state: ${reference.kind}`);
  }
  return {local, setup, stop};
}

const indent = (text, spaces) => text.split('\n').map(line => ' '.repeat(spaces) + line).join('\n');

export function buildChipComparisonExample() {
  const references = [
    ...FM_CALIBRATION_KINDS.map(kind => buildFmCalibrationReference(kind, 440)),
    ...PCM_CALIBRATION_KINDS.map(kind => buildPcmCalibrationReference(kind, 440)),
  ];
  if (references.length !== 21 || new Set(references.map(({kind}) => kind)).size !== 21) {
    throw new Error('Chip comparison must cover exactly the 21 public additional chip kinds');
  }
  const entries = references.map((reference, index) => {
    const {local, setup, stop} = standaloneReference(reference);
    const label = `Chip comparison ${String(index + 1).padStart(2, '0')}/21: ${reference.kind} · ${reference.waveform} · 440 Hz`;
    return `  async () => {
    const ${local} = await createSoundChip(${JSON.stringify(reference.kind)});
    try {
${indent(setup, 6)}
      log(${JSON.stringify(label)});
      await sleep(NOTE_SECONDS);
${indent(stop, 6)}
      await sleep(RELEASE_SECONDS);
    } finally {
      await ${local}.dispose();
    }
  }`;
  });
  return `// Generated by scripts/build_playground_chip_comparison.mjs from the measured reference tones.
// Mixer → Preset: System を選んで Run。Console で現在の音源を確認できます。
// Select Mixer → Preset: System before Run; this example preserves saved Mixer values.
// Web Audio / Native, Main / Worker: all 21 additional chip kinds, one at a time.
// Each plays A4 (440 Hz, hardware pitch quantization remains) for the same 1.2 seconds.
// FM/PCM use sine references; Sega PSG, AY and NES pulse use square references.
// SNES/SPC BRR uses symmetric 7/8 input headroom to avoid hardware interpolation overflow.
// Equal amplitude does not mean equal perceived loudness. Compare the steady middle of each tone.
// FX are cleared for this comparison; chip Mixer gains, pan, mute and solo are never changed.
// Stop cancels the current wait; finally disposes the chip without writing to a retired core.
// 間隔は Worker の先読み設定より長くし、最後の音源の破棄も待ちます。
const NOTE_SECONDS = 1.2;
const RELEASE_SECONDS = 0.08;
const timing = await getTiming();
const GAP_SECONDS = Math.max(0.35, timing.workerLookaheadSeconds + 0.1);

const comparisons = [
${entries.join(',\n')}
];

await fx.setChain([]);
log('Mixer → Preset: System を選んで Run。Console で現在の音源を確認。保存済み Mixer 値は変更しません。');
log('Chip comparison: 21 chips · 440 Hz · 1.2 s each · SNES/SPC BRR: 7/8 headroom');
for (let index = 0; index < comparisons.length; index++) {
  await comparisons[index]();
  await sleep(GAP_SECONDS);
}
log('Chip comparison complete: 21/21');
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = buildChipComparisonExample();
  if (process.argv.includes('--check')) {
    if (await readFile(CHIP_COMPARISON_TARGET, 'utf8') !== source) {
      throw new Error('Chip comparison example is stale; run node scripts/build_playground_chip_comparison.mjs');
    }
  } else await writeFile(CHIP_COMPARISON_TARGET, source);
}
