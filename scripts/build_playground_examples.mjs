// Bundle source files as strings: loading the Playground must never execute example code.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import {EXAMPLE_FOLDER_ORDER} from '../docs/playground/playground_example_order.js';
import {MODE_STARTERS, selectModeExamples} from '../docs/playground/playground_mode_examples.js';
const root = new URL('../docs/playground/examples/', import.meta.url);
const target = new URL('../docs/playground/playground_examples.js', import.meta.url);

export async function buildExampleBundle() {
  const files = [];
  const names = new Set();
  async function walk(relative = '') {
    const entries = await readdir(new URL(relative, root), {withFileTypes: true});
    const rank = entry => !relative && entry.isDirectory() && EXAMPLE_FOLDER_ORDER.includes(entry.name)
      ? EXAMPLE_FOLDER_ORDER.indexOf(entry.name) : EXAMPLE_FOLDER_ORDER.length;
    entries.sort((a,b) => rank(a) - rank(b) || (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
    for (const entry of entries) {
      const path = relative + entry.name;
      if (entry.isDirectory()) await walk(path + '/');
      else if (entry.name.endsWith('.js')) {
        const name = entry.name.slice(0,-3);
        if (names.has(name)) throw new Error(`Duplicate example name: ${name}`);
        names.add(name);
        files.push({path: '/examples/' + path, name, data: await readFile(new URL(path, root), 'utf8')});
      }
    }
  }
  await walk();
  const defaultCode = await readFile(new URL("../docs/playground/defaults/index.js", import.meta.url), "utf8");
  const modeDefaults = Object.fromEntries(await Promise.all(Object.entries(MODE_STARTERS).map(async ([id, definition]) =>
    [id, await readFile(new URL(`../docs/playground/defaults/${definition.index}`, import.meta.url), 'utf8')])));
  const modeExamplePaths = Object.fromEntries(Object.keys(MODE_STARTERS).map(id => [id,
    selectModeExamples(files, id).map(file => file.path)]));
  return '// Generated by scripts/build_playground_examples.mjs. Edit examples/**/*.js, defaults/**/index.js or playground_mode_examples.js instead.\n' +
    'export const DEFAULT_CODE = ' + JSON.stringify(defaultCode) + ';\n' +
    'export const MODE_DEFAULT_CODES = ' + JSON.stringify(modeDefaults,null,2) + ';\n' +
    'export const EXAMPLE_FILES = ' + JSON.stringify(files,null,2) + ';\n' +
    'export const EXAMPLES = Object.fromEntries(EXAMPLE_FILES.map(file => [file.name, file.data]));\n' +
    'const exampleByPath = new Map(EXAMPLE_FILES.map(file => [file.path, file]));\n' +
    'export const MODE_EXAMPLE_FILES = Object.fromEntries(Object.entries(' + JSON.stringify(modeExamplePaths,null,2) +
    ').map(([id, paths]) => [id, paths.map(path => exampleByPath.get(path))]));\n';
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = await buildExampleBundle();
  if (process.argv.includes('--check')) {
    if (await readFile(target,'utf8') !== source) throw new Error('Example bundle is stale; run node scripts/build_playground_examples.mjs');
  } else await writeFile(target, source);
}
